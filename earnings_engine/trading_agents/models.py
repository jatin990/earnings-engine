"""Data structures and schemas for TradingAgents Multi-Agent framework.

Defines the output schemas for:
1. Fundamental Analyst (Valuation, EPS Surprises, Growth, Financial Solvency)
2. Technical Analyst (Trend, Moving Averages, RSI, MACD, Volume Profile, S/R)
3. Sentiment & News Analyst (Corporate News Catalysts, Institutional Flows, Macro Sentiment)
4. Bullish Researcher (Upside Thesis, Growth Catalysts, Upside Target)
5. Bearish Researcher (Downside Risks, Headwinds, Failure Modes)
6. Risk & Portfolio Manager (Volatility, Invalidation Stop Loss, Max Loss, Sizing, RRR)
7. Head Trader (Final Action, Target, Conviction %, Time Horizon, Execution Summary)
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any


@dataclass
class FundamentalAnalystReport:
    """Findings from the Fundamental Analyst Agent."""

    score: float = 5.0                          # 1.0 - 10.0 scale
    stance: str = "NEUTRAL"                     # BULLISH | NEUTRAL | BEARISH
    pe_ratio: float | None = None
    peg_ratio: float | None = None
    pb_ratio: float | None = None
    eps_surprise_streak: int = 0
    earnings_quality_score: float | None = None # 1.0 - 9.0 scale
    revenue_growth_pct: float | None = None
    debt_to_equity: float | None = None
    summary: str = ""
    key_metrics: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class TechnicalAnalystReport:
    """Findings from the Technical Analyst Agent."""

    score: float = 5.0                          # 1.0 - 10.0 scale
    stance: str = "NEUTRAL"                     # BULLISH | NEUTRAL | BEARISH
    trend_posture: str = "RANGEBOUND"           # UPTREND | DOWNTREND | RANGEBOUND
    current_price: float = 0.0
    support_level: float = 0.0
    resistance_level: float = 0.0
    rsi_14: float | None = None
    macd_signal: str = "NEUTRAL"
    above_20_ema: bool = False
    above_50_ema: bool = False
    above_200_ema: bool = False
    volume_surge_ratio: float = 1.0
    volatility_atr_pct: float = 2.0
    chart_pattern: str = ""
    summary: str = ""
    key_signals: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SentimentAnalystReport:
    """Findings from the Sentiment & News Analyst Agent."""

    score: float = 5.0                          # 1.0 - 10.0 scale
    stance: str = "NEUTRAL"                     # BULLISH | NEUTRAL | BEARISH
    catalyst_direction: str = "NEUTRAL"
    catalyst_impact_score: float = 50.0         # 0 - 100%
    catalyst_headline: str = ""
    institutional_verdict: str = "Neutral"
    funds_accumulating_count: int = 0
    institutional_net_flow_cr: float = 0.0
    macro_regime_pill: str = "🟡 Neutral"
    summary: str = ""
    catalysts: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class BullResearcherReport:
    """Findings from the Bullish Researcher Agent."""

    conviction_pct: int = 50                    # 0 - 100%
    target_price: float = 0.0
    target_gain_pct: float = 0.0
    core_thesis: str = ""
    top_catalysts: list[str] = field(default_factory=list)
    time_horizon_days: int = 14

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class BearResearcherReport:
    """Findings from the Bearish Researcher Agent."""

    conviction_pct: int = 50                    # 0 - 100%
    downside_floor: float = 0.0
    downside_risk_pct: float = 0.0
    core_thesis: str = ""
    top_risks: list[str] = field(default_factory=list)
    invalidation_points: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class RiskManagerReport:
    """Assessment from the Risk & Portfolio Manager Agent."""

    volatility_risk: str = "MODERATE"           # LOW | MODERATE | HIGH | EXTREME
    stop_loss_price: float = 0.0
    max_downside_pct: float = 0.0
    risk_reward_ratio: float = 2.0
    recommended_position_pct: float = 10.0      # % of portfolio equity
    invalidation_criteria: str = ""
    risk_notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class TradingAgentsReport:
    """Master Synthesized Multi-Agent Report generated by Head Trader."""

    ticker: str
    company_name: str = ""
    industry: str = ""
    current_price: float = 0.0
    asof_date: str = ""
    timeframe_days: int = 14

    # Executive Head Trader Verdict
    action: str = "HOLD"                        # STRONG_BUY | BUY | HOLD | SELL | STRONG_SELL
    conviction_score: int = 50                  # 0 - 100%
    direction: str = "NEUTRAL"                  # BULLISH | BEARISH | NEUTRAL
    target_price: float = 0.0
    target_return_pct: float = 0.0
    stop_loss_price: float = 0.0
    risk_reward_ratio: float = 2.0
    execution_timing: str = "WAIT_FOR_DIP"      # IMMEDIATE | ON_BREAKOUT | ON_DIP | AVOID
    executive_summary: str = ""

    # Individual Agent Reports
    fundamental_analyst: FundamentalAnalystReport = field(default_factory=FundamentalAnalystReport)
    technical_analyst: TechnicalAnalystReport = field(default_factory=TechnicalAnalystReport)
    sentiment_analyst: SentimentAnalystReport = field(default_factory=SentimentAnalystReport)
    bull_researcher: BullResearcherReport = field(default_factory=BullResearcherReport)
    bear_researcher: BearResearcherReport = field(default_factory=BearResearcherReport)
    risk_manager: RiskManagerReport = field(default_factory=RiskManagerReport)

    # Debate Transcript & Reasoning
    debate_summary: str = ""
    key_drivers: list[str] = field(default_factory=list)
    primary_risks: list[str] = field(default_factory=list)
    
    # Metadata
    models_used: list[str] = field(default_factory=list)
    duration_s: float = 0.0
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "ticker": self.ticker,
            "company_name": self.company_name,
            "industry": self.industry,
            "current_price": round(self.current_price, 2),
            "asof_date": self.asof_date,
            "timeframe_days": self.timeframe_days,
            "action": self.action,
            "conviction_score": self.conviction_score,
            "direction": self.direction,
            "target_price": round(self.target_price, 2),
            "target_return_pct": round(self.target_return_pct, 2),
            "stop_loss_price": round(self.stop_loss_price, 2),
            "risk_reward_ratio": round(self.risk_reward_ratio, 2),
            "execution_timing": self.execution_timing,
            "executive_summary": self.executive_summary,
            "fundamental_analyst": self.fundamental_analyst.to_dict(),
            "technical_analyst": self.technical_analyst.to_dict(),
            "sentiment_analyst": self.sentiment_analyst.to_dict(),
            "bull_researcher": self.bull_researcher.to_dict(),
            "bear_researcher": self.bear_researcher.to_dict(),
            "risk_manager": self.risk_manager.to_dict(),
            "debate_summary": self.debate_summary,
            "key_drivers": self.key_drivers,
            "primary_risks": self.primary_risks,
            "models_used": self.models_used,
            "duration_s": round(self.duration_s, 2),
            "created_at": self.created_at,
        }
